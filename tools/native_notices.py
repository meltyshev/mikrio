"""Generate artifact notices from a locked binding dependency tree and target."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import tomllib
from collections.abc import Mapping, Sequence
from pathlib import Path

from tools.artifacts import ROOT, digest
from tools.native_runtime import TARGETS


def generate(
    target: str,
    binding: str = "python",
    *,
    offline: bool = False,
    cargo: Sequence[str] = ("cargo",),
    env: Mapping[str, str] | None = None,
) -> str:
    if binding not in {"python", "node", "ffi", "cli"}:
        raise ValueError("unknown native binding")

    distributions = [
        tomllib.loads(path.read_text(encoding="utf-8"))["package"]
        for path in sorted((ROOT / "vendor").glob("*/Cargo.toml"))
    ]

    maintained = {(item["name"], item["version"]) for item in distributions}

    upstream = {
        item["name"]: {
            "name": item["metadata"]["mikrio"]["upstream-name"],
            "version": item["metadata"]["mikrio"]["upstream-version"],
        }
        for item in distributions
    }

    flags = ["--locked"]

    if offline:
        flags.append("--offline")

    metadata = json.loads(
        subprocess.check_output(
            [*cargo, "metadata", *flags, "--format-version", "1"],
            cwd=ROOT,
            encoding="utf-8",
            env=env,
        )
    )

    targets = tuple(TARGETS.values()) if target == "supported" else (target,)

    trees = [
        subprocess.check_output(
            [
                *cargo,
                "tree",
                *flags,
                "-p",
                f"mikrio-{binding}",
                "--target",
                selected,
                "--prefix",
                "none",
                "--format",
                "{p}",
            ],
            cwd=ROOT,
            encoding="utf-8",
            env=env,
        )
        for selected in targets
    ]

    identities = set(re.findall(r"^([\w-]+) v(\S+)", "\n".join(trees), re.MULTILINE))

    packages = sorted(
        (
            package
            for package in metadata["packages"]
            if (
                package["source"] or (package["name"], package["version"]) in maintained
            )
            and (package["name"], package["version"]) in identities
        ),
        key=lambda package: (package["name"], package["version"]),
    )

    if not packages:
        raise ValueError("empty native dependency tree")

    output = [
        f"Generated by tools/native_notices.py --target {target}"
        + (f" --binding {binding}" if binding != "python" else "")
        + ".\n"
        "Inputs: Cargo.lock, target Cargo tree and registry license/notice files.\n"
        "Includes build-time inputs; regenerate after graph/target changes.\n",
        "Project: mikrio, Apache-2.0\n"
        + (ROOT / "LICENSE").read_text(encoding="utf-8"),
    ]

    for package in packages:
        source = Path(package["manifest_path"]).parent

        notices = sorted(
            (
                path
                for path in source.rglob("*")
                if path.is_file()
                and not path.is_relative_to(source / "target")
                and path.name.upper().startswith(("LICENSE", "COPYING", "NOTICE"))
            ),
            key=lambda path: path.relative_to(source).as_posix(),
        )

        output.append(
            f"\n{'=' * 72}\n{package['name']} {package['version']}: {package['license']}\n"
        )

        if not notices:
            supplements = json.loads(
                (ROOT / "vendor/licenses/sources.json").read_text(encoding="utf-8")
            )

            original = upstream.get(package["name"], package)
            supplement = supplements.get(f"{original['name']}@{original['version']}")

            if (
                not supplement
                or digest(ROOT / supplement["path"]) != supplement["sha256"]
            ):
                raise ValueError(
                    f"no reviewed license text found for {package['name']}"
                )

            output.append(
                f"\nSource: {supplement['source']}\n"
                + (ROOT / supplement["path"]).read_text(encoding="utf-8")
            )

        for notice in notices:
            output.append(
                f"\n--- {notice.relative_to(source).as_posix()} ---\n{notice.read_text(encoding='utf-8')}\n"
            )

        if package["name"] == "mikrio-libsqlite3-sys":
            sqlite = (source / "sqlite3/sqlite3.c").read_text(encoding="utf-8")

            blessing = sqlite.split(
                "** The author disclaims copyright to this source code.", 1
            )

            if len(blessing) != 2:
                raise ValueError("bundled SQLite public-domain notice changed")

            output.append(
                "\nSQLite: public domain.\nThe author disclaims copyright to this source code."
                + blessing[1].split("*/", 1)[0]
                + "\n"
            )

    # Preserve notice wording and source provenance while avoiding upstream
    # trailing spaces in generated repository/package text.
    return (
        "\n".join(line.rstrip() for line in "\n".join(output).splitlines()).rstrip()
        + "\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)

    parser.add_argument(
        "--target",
        required=True,
        help="Cargo target, or supported for the five-target notice union",
    )

    parser.add_argument(
        "--binding", choices=["python", "node", "ffi", "cli"], default="python"
    )

    parser.add_argument("--offline", action="store_true")
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()

    destinations = {
        "python": "packages/python/mikrio/THIRD_PARTY_LICENSES.txt",
        "node": "packages/node/THIRD_PARTY_LICENSES.txt",
        "ffi": "crates/mikrio-ffi/THIRD_PARTY_LICENSES.txt",
        "cli": "crates/mikrio-cli/THIRD_PARTY_LICENSES.txt",
    }

    path = ROOT / destinations[arguments.binding]
    content = generate(arguments.target, arguments.binding, offline=arguments.offline)

    if arguments.check:
        if path.read_text(encoding="utf-8") != content:
            raise ValueError("native notices need regeneration")
    else:
        path.write_text(content, encoding="utf-8", newline="\n")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
